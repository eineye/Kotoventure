#!/usr/bin/env python3
"""Build shared/src/i18n/dict/{ja,zh,es}.ts from translation tables.

usage: build-dict.py <source.tsv>... --tl <dir>
  source.tsv : <key>\t<English>        (key = fnv32 base36 of the normalised English, see translate.ts)
  <dir>/<lang>-*.tsv : <key>\t<translation>
Numbers in a translation must appear in the same order as in the English text; then the entry is stored
with # placeholders (shared by all numbers). Otherwise it is stored as an exact entry ('=' + fnv(English)).
"""
import glob, json, re, sys, os

NUM = re.compile(r'₩?[0-9][0-9,.:]*[0-9]|₩?[0-9]')

def fnv(s: str) -> str:
    h = 2166136261
    data = s.encode('utf-16-le')
    for i in range(0, len(data), 2):
        h ^= data[i] | (data[i + 1] << 8)
        h = (h * 16777619) & 0xFFFFFFFF
    n, out = h, ''
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    while True:
        n, r = divmod(n, 36)
        out = digits[r] + out
        if n == 0: break
    return out

args = sys.argv[1:]
tl = args[args.index('--tl') + 1]
sources = [a for a in args[:args.index('--tl')]]
en = {}
for f in sources:
    for line in open(f, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line: continue
        k, s = line.split('\t', 1)
        en[k] = s.replace('\\n', '\n')
root = os.path.join(os.path.dirname(__file__), '..', 'src', 'i18n', 'dict')
for lang in ['ja', 'zh', 'es']:
    tr = {}
    for f in sorted(glob.glob(os.path.join(tl, f'{lang}-*.tsv'))):
        for line in open(f, encoding='utf-8'):
            line = line.rstrip('\n')
            if not line: continue
            k, s = line.split('\t', 1)
            if k not in en: print(f'{lang}: unknown key {k} in {f}'); continue
            tr[k] = s.replace('\\n', '\n')
    d, exact = {}, 0
    for k, t in tr.items():
        src = en[k]
        if NUM.findall(src) == NUM.findall(t):
            d[k] = NUM.sub('#', t)
        else:
            d['=' + fnv(src)] = t; exact += 1
    missing = [k for k in en if k not in tr]
    print(f'{lang}: {len(tr)} translated, {exact} exact-only, {len(missing)} missing')
    lines = ['/** Generated by scripts/build-dict.py – do not edit by hand. Key: fnv32 of the normalised English text (numbers → #). */', 'export const DICT: Record<string, string> = {']
    for k in sorted(d): lines.append(f'  {json.dumps(k)}: {json.dumps(d[k], ensure_ascii=False)},')
    lines.append('};\n')
    open(os.path.join(root, f'{lang}.ts'), 'w', encoding='utf-8').write('\n'.join(lines))
