/** Generates supabase/seed.sql from the bundled seed content (idempotent upserts). */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { SEED_BUNDLE } from '../src';

// columns stored as Postgres text[] (everything else that is an object/array is jsonb)
const TEXT_ARRAY_COLS = new Set(['course_ids']);

const q = (v: unknown, col = ''): string => {
  if (v === undefined || v === null) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (TEXT_ARRAY_COLS.has(col) && Array.isArray(v)) return `array[${v.map((x) => q(x)).join(',')}]::text[]`;
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (vals: unknown[], cols: string[]) => `(${vals.map((v, i) => q(v, cols[i])).join(', ')})`;
const upsert = (table: string, cols: string[], rows: unknown[][], key: string[]) =>
  rows.length
    ? `insert into public.${table} (${cols.join(', ')}) values\n  ${rows.map((r) => row(r, cols)).join(',\n  ')}\non conflict (${key.join(', ')}) do update set ${cols
        .filter((c) => !key.includes(c))
        .map((c) => `${c} = excluded.${c}`)
        .join(', ')};\n\n`
    : '';

const b = SEED_BUNDLE;
let sql = `-- AUTO-GENERATED by shared/scripts/build-seed.ts – do not edit by hand.\n-- Run: cd shared && npm run seed:sql\n\n`;
sql += upsert('categories', ['id', 'name', 'icon', 'color', 'sort_order', 'is_active'],
  b.categories.map((c) => [c.id, c.name, c.icon, c.color, c.sortOrder, c.isActive]), ['id']);
sql += upsert('cards', ['id', 'topic', 'title', 'body', 'prop', 'phrase', 'tips'],
  b.cards.map((c) => [c.id, c.topic, c.title, c.body, c.prop, c.phrase, c.tips ?? []]), ['id']);
sql += upsert('products', ['id', 'type', 'title', 'price_usd', 'ios_product_id', 'android_product_id', 'course_ids', 'is_active'],
  b.products.map((p) => [p.id, p.type, p.title, p.priceUsd, p.iosProductId, p.androidProductId, p.courseIds, p.isActive]), ['id']);
sql += upsert('courses',
  ['id', 'category_id', 'area', 'title', 'subtitle', 'description', 'region', 'entry', 'exit', 'nights', 'days', 'difficulty', 'party_fit', 'party_tips', 'start_budget', 'cover_bg', 'access', 'product_id', 'is_published', 'version', 'sort_order'],
  b.courses.map((c) => [c.id, c.categoryId, c.area ?? null, c.title, c.subtitle, c.description, c.region, c.entry, c.exit, c.nights, c.days, c.difficulty, c.partyFit, c.partyTips, c.startBudget, c.coverBg, c.access, c.productId ?? null, c.isPublished, c.version, c.sortOrder]),
  ['id']);
sql += upsert('scenes', ['id', 'course_id', 'sort_order', 'day', 'title', 'location', 'bg', 'steps'],
  b.courses.flatMap((c) => c.scenes.map((s, i) => [s.id, c.id, i, s.day, s.title, s.location, s.bg, s.steps])), ['course_id', 'id']);
sql += upsert('app_config', ['key', 'value'], [['main', b.config]], ['key']);
sql += upsert('treks', ['id', 'status', 'area', 'data'], (b.treks ?? []).map((x) => [x.id, x.status, x.area, x]), ['id']);
sql += upsert('spots', ['id', 'status', 'area', 'sponsored', 'data'], (b.spots ?? []).map((x) => [x.id, x.status, x.area, x.sponsored, x]), ['id']);

const out = resolve(__dirname, '../../supabase/seed.sql');
writeFileSync(out, sql);
console.log(`wrote ${out} (${(sql.length / 1024).toFixed(0)} KB)`);
